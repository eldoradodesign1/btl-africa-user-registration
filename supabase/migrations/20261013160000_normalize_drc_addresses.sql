-- BTL Africa: normalized DRC address reference and profile address fields.
-- Sources: CENI 2023 cities/communes reference and HDX/OpenStreetMap RDC quartiers 2022.
-- The OSM quartier source is partial; the UI therefore supports a clearly-labelled manual fallback.

create table if not exists public.address_provinces (id text primary key, name text not null unique, code text unique, source text not null default 'CENI/Ministère de l’Intérieur');
create table if not exists public.address_communes (id text primary key, province_id text not null references public.address_provinces(id) on delete cascade, name text not null, source text not null default 'CENI 2023', unique (province_id, name));
create table if not exists public.address_quartiers (id text primary key, province_id text not null references public.address_provinces(id) on delete cascade, commune_name text not null, name text not null, source text not null default 'HDX / OpenStreetMap RDC 2022', unique (province_id, commune_name, name));
create index if not exists address_communes_province_idx on public.address_communes(province_id, name);
create index if not exists address_quartiers_commune_idx on public.address_quartiers(province_id, commune_name, name);

